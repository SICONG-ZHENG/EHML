
#' Feature Selection Using Multiple Machine Learning Algorithms
#'
#' @description
#' Performs feature selection on the training dataset using
#' Elastic Net, Lasso, stepwise logistic regression, GLMBoost,
#' sparse PLS-GLM, random forest, random forest SRC,
#' gradient boosting machines (GBM), and Boruta.
#'
#' Multiple feature-selection methods are applied independently,
#' and the selected feature sets are returned as a named list.
#'
#' @param Object A list containing `train_data` and `train_label`.
#'   The `train_data` component contains predictor variables,
#'   and `train_label` contains binary outcome labels encoded as 0 and 1.
#'
#' @param allgene A character vector specifying candidate predictors.
#'   By default, all columns of `Object$train_data` are used.
#'
#' @param fold A positive integer specifying the number of
#'   cross-validation folds. Defaults to 10.
#'
#' @param seed A positive integer specifying the random seed
#'   for reproducibility. Defaults to 123.
#'
#' @details
#' The function performs feature selection using multiple
#' machine learning algorithms.
#'
#' Elastic Net models are fitted with alpha values ranging
#' from 0.1 to 0.9.
#'
#' Lasso uses an alpha value of 1.
#'
#' Stepwise logistic regression includes forward,
#' backward, and bidirectional selection.
#'
#' GLMBoost and sparse PLS-GLM select variables according
#' to non-zero regression coefficients.
#'
#' Random forest, random forest SRC, and GBM use
#' variable importance measures for feature selection.
#'
#' Boruta identifies relevant predictors using
#' an all-relevant feature selection strategy.
#'
#' Feature sets with no selected predictors are removed.
#' Feature sets containing all candidate predictors are
#' excluded, except for the original complete feature set.
#' Duplicate Elastic Net feature sets are also removed.
#'
#' @return A named list of character vectors.
#'   Each element represents a selected feature set.
#'   The list includes the complete candidate feature set
#'   and non-empty feature sets generated by the
#'   feature-selection algorithms.
#'
#' @export
#'
features <- function(Object,
                     allgene=colnames(Object$train_data),
                     fold=10,
                     seed=123){
  ###ALL
  gene=list()
  gene[[paste0("All ",length(allgene)," genes")]] <-allgene
  #######
  train <- Object$train_data
  train_matrix <- as.matrix(train[,allgene,drop=F])
  labels <-  Object$train_label
  labels_numeric <- labels[,1]
  labels_factor <- factor(ifelse(labels_numeric%in% 0, 0 ,1),levels = c(0,1))
  train1 <- train
  train1$labels <- labels_factor
  ######add Enet to select gene
  for (alpha in seq(0.1,0.9,0.1)) {
    set.seed(seed)
    cvfit <- glmnet::cv.glmnet(train_matrix, labels_factor, family = "binomial",
                               nlambda=1000, alpha=alpha,nfolds = fold)
    coef <- coef(cvfit, s = cvfit$lambda.min)
    Enetgene <- row.names(coef)[which(coef[,1] != 0)]
    Enetgene <- setdiff(Enetgene, c("(Intercept)", "Intercept"))
    gene[[paste0("Enet ",length(Enetgene)," genes","[alpha=",alpha,"]")]] <-Enetgene
  }
  seen <- list()
  gene_new <- list()
  gene_new[[names(gene)[1]]] <- gene[[1]]
  for(i in 2:length(gene)){
    x <- sort(gene[[i]])
    key <- paste(x, collapse = "|")
    if(!(key %in% names(seen))){
      seen[[key]] <- TRUE
      gene_new[[names(gene)[i]]] <- gene[[i]]
    }
  }
  gene <- gene_new
  ###### add lasso to select gene
  set.seed(seed)
  cvfit <- glmnet::cv.glmnet(train_matrix, labels_factor, family = "binomial",
                             nlambda=100, alpha=1,nfolds = fold)
  coef <- coef(cvfit, s = cvfit$lambda.min)
  lassogene <- row.names(coef)[which(coef[,1] != 0)]
  lassogene <- setdiff(lassogene, c("(Intercept)", "Intercept"))
  gene[[paste0("Lasso ",length(lassogene)," genes")]] <-lassogene
  #####Stepglm
  #####both
  fit <- step(stats::glm(labels~., family = "binomial", data = train1,
                         control = glm.control(maxit = 100)),
              direction = "both", trace = 0)
  Stepglm_both <- names(coef(fit))
  Stepglm_both <- setdiff(Stepglm_both, c("(Intercept)", "Intercept"))
  gene[[paste0("Stepglm [both] ",length(Stepglm_both)," genes")]] <-Stepglm_both
  ####backward
  fit <- step(stats::glm(labels~.-labels, family = "binomial", data = train1,
                         control = glm.control(maxit = 100)),
              direction = "backward", trace = 0)
  Stepglm_backward <- names(coef(fit))
  Stepglm_backward <- setdiff(Stepglm_backward, c("(Intercept)", "Intercept"))
  gene[[paste0("Stepglm [backward] ",length(Stepglm_backward)," genes")]] <-Stepglm_backward
  ###forward
  null_fit <- stats::glm(labels ~ 1,family = 'binomial',data = train1)
  full_fit <- stats::glm(labels~., family = 'binomial', data = train1)
  fit <- MASS::stepAIC(null_fit, # start with a model containing no variables
                       direction = 'forward', # run forward selection
                       scope = list(upper = full_fit, # the maximum to consider is a model with all variables
                                    lower = null_fit), # the minimum to consider is a model with no variables
                       trace = 0)
  Stepglm_forward <- names(coef(fit))
  Stepglm_forward <- setdiff(Stepglm_forward, c("(Intercept)", "Intercept"))
  gene[[paste0("Stepglm [forward] ",length(Stepglm_forward)," genes")]] <-Stepglm_forward
  ##########################glmboost########
  ########As glmboost does not directly return a set of selected variables,
  #######features with non-zero regression coefficients were retained,
  #######while variables with coefficients equal to zero were discarded and
  #######considered unselected.
  fit <- mboost::glmboost(labels ~ .,data = train1,family = mboost::Binomial())
  set.seed(seed)
  cvm <- mboost::cvrisk(fit, papply = lapply,
                        folds = mboost::cv(stats::model.weights(fit), type = "kfold"))
  fit <- mboost::glmboost(labels ~ .,
                          data = train1,
                          family = mboost::Binomial(),
                          control = mboost::boost_control(mstop = max(mboost::mstop(cvm), 40)))
  coef_fit <- coef(fit)
  glmboost_gene <- names(coef_fit)[abs(coef_fit) > 0]
  glmboost_gene <- setdiff(glmboost_gene,"(Intercept)")
  gene[[paste0("Glmboost ",length(glmboost_gene)," genes")]] <-glmboost_gene
  #########################plsRglmmodel#######################
  #######As PLSRglm does not directly perform feature selection,
  ######variables with non-zero regression coefficients were considered selected,
  ######whereas variables with coefficients equal to zero were discarded
  set.seed(seed)
  fit <- plsRglm::plsRglm( train1$labels,
                           train1[, setdiff(colnames(train1), "labels")],
                           modele = "pls-glm-logistic",
                           verbose = FALSE, sparse = TRUE)
  coef_fit <- fit$Coeffs
  plsRglm_gene <- rownames(coef_fit)[coef_fit!=0]
  plsRglm_gene <- setdiff(plsRglm_gene, c("(Intercept)", "Intercept"))
  gene[[paste0("PlsRglm ",length(plsRglm_gene)," genes")]] <-plsRglm_gene
  ###################################### randomForest:RF
  set.seed(seed)
  fit <- randomForest::randomForest(labels~., data = train1, ntree=10000, importance = TRUE)
  oob <- fit$err.rate[,1]
  min_err <- min(oob)
  best_tree <- which(oob == min_err)[1]
  set.seed(seed)
  fit <- randomForest::randomForest(labels~., data = train1, ntree=best_tree, nodesize =5,
                                    proximity = T,
                                    importance = TRUE)
  imp <- fit$importance
  imp <- data.frame(imp)
  RF_gene <- rownames(imp)[imp$MeanDecreaseAccuracy>0.01]
  gene[[paste0("RF ",length(RF_gene)," genes")]] <-RF_gene
  #########################RSF
  set.seed(seed)
  fit <- randomForestSRC::rfsrc(labels~.,data = train1,ntree = 10000, nodesize = 5,
                                importance = T,proximity = T,forest = T)
  RSF_gene <-  names(which(fit$importance[,1] > 0.01))
  gene[[paste0("RSF ",length(RSF_gene)," genes")]] <-RSF_gene
  ########################GBM
  train2 <- train1
  train2$labels <- labels_numeric
  n_cv_train <- floor(nrow(train2) * (fold - 1) / fold)
  min_bag <- 22 / n_cv_train
  bag.fraction <- min(1,max(0.5, min_bag + 0.05))
  set.seed(seed)
  fit <- gbm::gbm(labels~., data = train2,
                  distribution = "bernoulli", n.trees = 10000,interaction.depth = 3,
                  shrinkage = 0.001,cv.folds = fold,n.cores = 6,
                  bag.fraction = bag.fraction,
                  n.minobsinnode = 10)
  best <- which.min(fit$cv.error)
  set.seed(seed)
  fit <- gbm::gbm(labels~., data = train2,
                  distribution = 'bernoulli',n.trees = best,interaction.depth = 3,
                  bag.fraction = bag.fraction,
                  shrinkage = 0.001,n.minobsinnode = 10,n.cores = 8)
  GBM_gene <- rownames(gbm::summary.gbm(fit, plotit = F))[gbm::summary.gbm(fit, plotit = F)$rel.inf>0]
  gene[[paste0("GBM ",length(GBM_gene)," genes")]] <-GBM_gene
  ###########################################Boruta
  set.seed(seed)
  boruta_fit <- Boruta::Boruta(labels ~ .,data = train1,maxRuns = 500,doTrace = 1)
  Boruta_gene <- Boruta::getSelectedAttributes(boruta_fit,withTentative = F)
  gene[[paste0("Boruta ",length(Boruta_gene)," genes")]] <-Boruta_gene
  ###########################################################################################
  all_name <- names(gene)[1]
  all_n <- length(gene[[1]])
  gene <- gene[(names(gene) == all_name |
                  sapply(gene, length) != all_n) &
                 sapply(gene, length) > 0]

  return(gene)
}



